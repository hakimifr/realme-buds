#!/usr/bin/env python3
"""Write docs/MODELS.md from the bundled device profiles: ``python3 scripts/make_models_doc.py``.

tests/test_docs.py fails when the file is out of date, so rerun this after changing a profile."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from realmebuds import profiles  # noqa: E402

TRIED_ON_REAL_BUDS = {"realme-buds-air7-pro"}
VENDOR_ORDER = {"realme": 0, "oppo": 1, "oneplus": 2, "dizo": 3}
VENDOR_LABEL = {"realme": "realme", "oppo": "OPPO", "oneplus": "OnePlus", "dizo": "DIZO"}


def anc_cell(p: profiles.DeviceProfile) -> str:
    if not p.has_anc:
        return "none"
    names = []
    for key in p.anc_buttons:
        grp = p.group(key)
        names.append("NC levels" if grp else p.mode(key).label)
    return ", ".join(names)


def status_cell(p: profiles.DeviceProfile) -> str:
    if p.key in TRIED_ON_REAL_BUDS:
        return "tried on real buds"
    if "confirmed on its owners" in p.notes or "QuickBuds confirmed" in p.notes:
        confirmed = p.notes.split("(")[1].split(")")[0] if "(" in p.notes else ""
        return f"data confirmed by QuickBuds owners ({confirmed})" if confirmed else "partly confirmed elsewhere"
    return "data only"


def render() -> str:
    shipped = profiles.load_all(extra_dirs=[])  # built-in only is what ships; user profiles are not listed
    builtin = {k: p for k, p in shipped.items() if p.source == "builtin"}
    rows = sorted(builtin.values(), key=lambda p: (VENDOR_ORDER.get(p.vendor, 9), p.name.lower(), p.key))
    out = [
        "# Models with a built-in profile",
        "",
        "Generated by `scripts/make_models_doc.py`, do not edit by hand.",
        "",
        f"**{len(rows)} models.** Having a profile does **not** mean the model works. A profile is data about the model:",
        "what its noise-control values mean, which feature switches it has, what each gesture can do. Only the",
        "realme Buds Air7 Pro has been tried on real buds, and only partly. Every other profile was converted from",
        "[QuickBuds](https://github.com/spizganed/QuickBuds)' model data (see [NOTICE.md](../NOTICE.md)) and has never been",
        "run on real hardware by this project. A model that only speaks Bluetooth LE needs `--transport ble`, which is",
        "also untested. If you try one, please tell me what worked.",
        "",
        "| Vendor | Model | Product id | Noise control | Hold cycle | Switches | Custom EQ | Golden Sound | Status |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for p in rows:
        eq = f"{len(p.custom_eq.freqs)} bands" if p.custom_eq else "-"
        hold = f"{len(p.hold_options)} modes" if p.hold_options else "-"
        out.append(
            f"| {VENDOR_LABEL.get(p.vendor, p.vendor)} | {p.name} | `{p.product_ids[0] if p.product_ids else '-'}` | {anc_cell(p)} | "
            f"{hold} | {len(p.features)} | {eq} | {'yes' if p.golden_sound else '-'} | {status_cell(p)} |"
        )
    out += ["", "Missing your model? See [ADDING_A_DEVICE.md](ADDING_A_DEVICE.md): `realme-buds profile detect` drafts one.", ""]
    return "\n".join(out)


def main() -> int:
    target = ROOT / "docs" / "MODELS.md"
    target.write_text(render(), encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
